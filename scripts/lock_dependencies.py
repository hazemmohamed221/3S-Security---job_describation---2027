"""Pin only the app/test dependency closure, never unrelated host packages."""
import argparse
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
APP_ROOTS = ('streamlit', 'python-docx', 'pandas', 'openpyxl', 'argon2-cffi')


def dependency_closure(roots):
    environments = []
    for system, platform, python in (('Windows', 'win32', '3.14'), ('Linux', 'linux', '3.11')):
        env = default_environment() | {'platform_system': system, 'sys_platform': platform,
                                      'python_version': python, 'python_full_version': python + '.0', 'extra': ''}
        environments.append(env)
    pinned, pending = {}, [Requirement(name) for name in roots]
    while pending:
        req = pending.pop()
        name = canonicalize_name(req.name)
        dist = metadata.distribution(name)
        if req.specifier and dist.version not in req.specifier:
            raise RuntimeError(f'Installed {name}=={dist.version} does not satisfy {req.specifier}')
        if name in pinned:
            continue
        pinned[name] = dist.version
        for raw in dist.requires or ():
            child = Requirement(raw)
            if child.marker is None or any(child.marker.evaluate(env) for env in environments):
                if child.extras:
                    raise RuntimeError(f'Explicit extra dependency requires review: {raw}')
                pending.append(child)
    return dict(sorted(pinned.items()))


def lock_text(pins):
    return ''.join(f'{name}=={version}\n' for name, version in sorted(pins.items()))


def generate(check=False):
    app = dependency_closure(APP_ROOTS)
    dev = dependency_closure((*APP_ROOTS, 'pytest'))
    outputs = {
        ROOT / 'requirements.lock': '# Exact app closure for Python 3.11+ on Windows/Linux; generated by scripts.lock_dependencies.\n' + lock_text(app),
        ROOT / 'requirements-dev.lock': '# Exact test dependencies in addition to the app lock.\n-r requirements.lock\n' + lock_text({k: v for k, v in dev.items() if k not in app}),
    }
    for path, content in outputs.items():
        if check:
            if path.read_text(encoding='utf-8') != content:
                raise RuntimeError(f'{path.name} differs from the tested installed dependency closure.')
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    return len(app), len(dev)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    app, dev = generate(args.check)
    print(f'Exact pins {"verified" if args.check else "generated"}: {app} app packages, {dev} including tests.')
